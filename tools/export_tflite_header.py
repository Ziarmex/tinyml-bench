"""Convert a .tflite flatbuffer into a C/C++ array header for TFLite Micro.

Usage:
    python tools/export_tflite_header.py model_int8.tflite model_data.h model_int8
"""
from __future__ import annotations

import argparse
from pathlib import Path


def bytes_to_c_array(data: bytes, name: str, bytes_per_line: int = 12) -> str:
    if bytes_per_line <= 0:
        raise ValueError("bytes_per_line must be > 0")
    rows = []
    for offset in range(0, len(data), bytes_per_line):
        chunk = data[offset:offset + bytes_per_line]
        rows.append("  " + ", ".join(f"0x{byte:02x}" for byte in chunk) + ",")
    body = "\n".join(rows)
    return (
        "// Auto-generated by tools/export_tflite_header.py. Do not edit.\n"
        "#include <stdint.h>\n\n"
        f"alignas(8) const unsigned char {name}[] = {{\n{body}\n}};\n"
        f"const unsigned int {name}_len = {len(data)};\n"
    )


def write_header(tflite_path: str | Path, out_path: str | Path,
                 name: str = "model_data") -> int:
    data = Path(tflite_path).read_bytes()
    Path(out_path).write_text(bytes_to_c_array(data, name))
    return len(data)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("tflite", help="input .tflite file")
    parser.add_argument("output", help="output C header path")
    parser.add_argument("--name", default="model_data", help="array symbol name")
    args = parser.parse_args()

    size = write_header(args.tflite, args.output, args.name)
    print(f"Wrote {args.output} ({size} bytes) as '{args.name}'")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
